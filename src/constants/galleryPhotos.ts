export function galleryFolderUrl(day: GalleryDaySlug): string {
  return `${GALLERY_SHARE_BASE}?path=${encodeURIComponent("/" + galleryFolderByDay[day])}`;
}

export function galleryPreviewUrl(
  day: GalleryDaySlug,
  fileName: string,
  width = 640,
  height = 428
): string {
  const params = new URLSearchParams({
    file: `/${galleryFolderByDay[day]}/${fileName}`,
    x: String(width),
    y: String(height),
    a: "1"
  });
  return `https://dms.uom.lk/index.php/apps/files_sharing/publicpreview/${GALLERY_SHARE_TOKEN}?${params.toString()}`;
}

